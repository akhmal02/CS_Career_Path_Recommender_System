def match_tier(percentage):
    if percentage >= 95:
        return "Perfect", "Your answers are exceptionally consistent with this career profile."
    if percentage >= 90:
        return "Great", "Your preferences strongly support this career, with only small gaps."
    if percentage >= 80:
        return "Good", "You have a solid foundation for this career and several areas align well."
    return "Exploratory", "This path has some relevant signals, but important preferences or skills do not yet align."
